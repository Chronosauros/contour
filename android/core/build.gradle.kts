// :core - pure Kotlin/JVM, zero Android dependencies (model, DSP, text codecs, device protocol).
plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.serialization)
}

providers.gradleProperty("contour.buildRoot").orNull?.let { layout.buildDirectory.set(file("$it/core")) }

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

// Device catalog: devices.gradle.kts registers :core:generateDeviceCatalog (device records in <repo>/devices -> GeneratedDevices.kt in the
// build dir); making the task a source dir of main is what makes compileKotlin depend on it. See devices/README.md.
apply(from = "devices.gradle.kts")

kotlin {
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
    sourceSets.getByName("main").kotlin.srcDir(tasks.named("generateDeviceCatalog"))
}

dependencies {
    api(libs.kotlinx.serialization.json)
    testImplementation(libs.kotlin.test)
}

// The parity test reads the device captures in research/protocol/ and, when present, the maintainer's profiles
// in a sibling eq-library folder (read-only). Paths are resolved from the repo root, which is android/.. .
val repoRoot: String = rootProject.projectDir.parentFile.absolutePath

tasks.withType<Test>().configureEach {
    useJUnitPlatform()
    systemProperty("contour.repoRoot", repoRoot)
    testLogging {
        events("passed", "failed", "skipped")
        showStandardStreams = true
    }
}

// The Android USB attach filter is generated by :app:generateUsbDeviceFilter from the same device records; the tests compare it with the app's
// recognition (DeviceRecognitionTest, CatalogGoldenTest). Task outputs are the test's inputs, so the filter is built first and a change reruns the tests.
// The file sits at <task output>/xml/device_filter.xml; the path is resolved at execution time.
val usbFilterTask = project(":app").tasks.named("generateUsbDeviceFilter")
tasks.withType<Test>().configureEach {
    inputs.files(usbFilterTask).withPathSensitivity(PathSensitivity.RELATIVE).withPropertyName("usbDeviceFilter")
    val filterDir = usbFilterTask.map { it.outputs.files.singleFile }
    jvmArgumentProviders.add(CommandLineArgumentProvider { listOf("-Dcontour.usbFilterXml=" + filterDir.get().resolve("xml/device_filter.xml").absolutePath) })
}

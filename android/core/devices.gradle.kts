// Device catalog generator for :core (applied from core/build.gradle.kts).
//
// Reads the strict-JSON records in <repo>/devices/*.json and writes one Kotlin file, GeneratedDevices, into the build
// directory; build.gradle.kts makes that directory a Kotlin source dir of :core, so compileKotlin runs this task first. Values are emitted as the
// EXISTING types (FiioConfig, FiioCaptureIdentity, SettingPlacement) or the plain data classes of core/devices/CatalogTypes.kt - no runtime JSON,
// no reflection. Behaviour (decoders, codecs, write sequences, the Micro high-shelf emulation) stays hand-written; only data moves here.
// See devices/README.md.
//
// What is generated, per family: every record -> its USB identity row (GeneratedDevices.USB_IDS, in `usb.listOrder`) and the <ID>_VENDOR_ID and
// <ID>_PRODUCT_ID constants; fiio -> FiioConfig; walkplay -> WalkPlayData (caps, preamp policy, factory flat, read bounds) or, for a record that is
// not stable, ReadOnlyWalkPlayData; moondrop -> MoondropData; ktmicro -> KtMicroData.
//
// Gate: a record must carry every key its driver needs, and none of them may be the placeholder "unknown" - the task throws, so the build
// fails. A value the code uses while its record still says "unknown" is not read from the record: it lives in core/devices/PendingRecords.kt
// until the record has a source for it. Free text (notes, conflicts, evidence, reset, hwVolume, src) is never read.
//
// No plugin and no network: groovy.json.JsonSlurper ships with Gradle's own classpath, so F-Droid builds stay offline.
import groovy.json.JsonSlurper
import java.io.File

abstract class GenerateDeviceCatalog : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val records: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val recs = mutableListOf<Pair<String, Map<String, Any?>>>()
        for (f in records.files.sortedBy { it.name }) recs += f.name to obj(JsonSlurper().parse(f), f.name)
        val ids = recs.map { str(it.second, "id", it.first) }
        if (ids.toSet().size != ids.size) fail("duplicate record ids: $ids")
        if (recs.none { str(it.second, "family", it.first) == "fiio" }) fail("no record with family \"fiio\" in devices/*.json")
        val walkplayReportIds = recs.filter { str(it.second, "family", it.first) == "walkplay" }
            .map { int(obj(field(it.second, "driver", it.first), "${it.first}.driver"), "reportId", it.first) }.toSet()
        if (walkplayReportIds.size > 1) fail("walkplay records disagree on driver.reportId: $walkplayReportIds (the WalkPlay code has one report id)")
        // The WalkPlay code has one design rate, and one band length per write sequence (WalkPlay.DESIGN_FS, BAND_LEN, TRN_BAND_LEN).
        val stableWalkplay = recs.filter { str(it.second, "family", it.first) == "walkplay" && str(it.second, "status", it.first) == "stable" }
            .map { obj(field(it.second, "driver", it.first), "${it.first}.driver") }
        if (stableWalkplay.map { field(it, "designRateHz", "driver") }.toSet().size > 1) fail("stable walkplay records disagree on driver.designRateHz")
        for ((sequence, group) in stableWalkplay.groupBy { field(it, "writeSequence", "driver") })
            if (group.map { field(it, "bandLen", "driver") }.toSet().size > 1) fail("stable walkplay records with writeSequence \"$sequence\" disagree on driver.bandLen")

        val out = StringBuilder()
        out.append("// GENERATED by :core:generateDeviceCatalog from devices/*.json - do not edit; change the record.\n")
        out.append("package io.github.chronosauros.contour.core.devices\n\n")
        out.append("import io.github.chronosauros.contour.core.FilterType\n")
        out.append("import io.github.chronosauros.contour.core.native.DacSettings\n")
        out.append("import io.github.chronosauros.contour.core.native.FiioCaptureIdentity\n")
        out.append("import io.github.chronosauros.contour.core.native.FiioConfig\n")
        out.append("import io.github.chronosauros.contour.core.native.SettingPlacement\n")
        out.append("import kotlin.math.sqrt\n\n")
        out.append("internal object GeneratedDevices {\n")
        usbIds(out, recs)
        for ((file, rec) in recs) when (val family = str(rec, "family", file)) {
            "fiio" -> fiioRecord(out, file, rec)
            "walkplay" -> if (str(rec, "status", file) == "stable") walkplayRecord(out, file, rec) else readOnlyWalkplayRecord(out, file, rec)
            "moondrop" -> moondropRecord(out, file, rec)
            "ktmicro" -> ktmicroRecord(out, file, rec)
            else -> fail("$file: family \"$family\" has no driver in the generator (fiio | walkplay | moondrop | ktmicro)")
        }
        out.append("}\n")

        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val target = File(dir, "io/github/chronosauros/contour/core/devices/DeviceCatalog.kt")
        target.parentFile.mkdirs()
        target.writeBytes(out.toString().toByteArray(Charsets.UTF_8))
    }

    // ---- USB identity of every record -------------------------------------------------------------------------------

    private fun usbIds(out: StringBuilder, recs: List<Pair<String, Map<String, Any?>>>) {
        class Row(val order: Int, val text: String, val key: String, val valName: String)
        val rows = recs.map { (file, rec) ->
            val id = str(rec, "id", file)
            val usb = obj(field(rec, "usb", id), "$id.usb")
            for (k in listOf("vid", "pid")) noUnknown(field(usb, k, "$id.usb"), "$id.usb.$k")
            val vid = usbId(field(usb, "vid", "$id.usb"), "$id.usb.vid")
            val pid = usbId(field(usb, "pid", "$id.usb"), "$id.usb.pid")
            val matchByName = bool(usb, "matchByName", "$id.usb")
            val productName = when (val v = field(usb, "productName", "$id.usb")) {
                "unknown" -> if (matchByName) fail("$id.usb.productName is \"unknown\" but usb.matchByName is true: a name match needs the name") else null
                is String -> v
                else -> fail("$id.usb.productName must be a string")
            }
            val aliases = if (usb.containsKey("nameAliases")) list(usb["nameAliases"], "$id.usb.nameAliases").map { it as? String ?: fail("$id.usb.nameAliases must hold strings") } else emptyList()
            if (aliases.isNotEmpty() && !matchByName) fail("$id.usb.nameAliases only count when usb.matchByName is true")
            val recognisedBy = when (val r = str(usb, "recognisedBy", "$id.usb")) {
                "find" -> "FIND"
                "findDevice" -> "FIND_DEVICE"
                else -> fail("$id.usb.recognisedBy \"$r\" is not find | findDevice")
            }
            if (recognisedBy == "FIND" && matchByName) fail("$id.usb.recognisedBy is \"find\" (VID:PID only, no product name) but usb.matchByName is true: use \"findDevice\"")
            val order = int(usb, "listOrder", "$id.usb")
            Row(order, "    val ${ident(id)}_USB: UsbIdentity = UsbIdentity(${ks(id)}, ${ks(str(rec, "name", id))}, $vid, $pid, ${productName?.let { ks(it) } ?: "null"}, $matchByName, " +
                "${if (aliases.isEmpty()) "emptyList()" else "listOf(" + aliases.joinToString(", ") { ks(it) } + ")"}, Recognition.$recognisedBy)\n",
                "%04X:%04X".format(vid, pid), "${ident(id)}_USB")
        }
        if (rows.map { it.order }.toSet().size != rows.size) fail("usb.listOrder is not unique across the records")
        if (rows.map { it.key }.toSet().size != rows.size) fail("two records share one USB VID:PID")
        out.append("\n")
        for (r in rows) out.append(r.text)
        out.append("\n    /** The USB identity of every record, in `usb.listOrder` (the order of the Android attach filter). */\n")
        out.append("    val USB_IDS: List<UsbIdentity> = listOf(${rows.sortedBy { it.order }.joinToString(", ") { it.valName }})\n")
    }

    private fun idConsts(out: StringBuilder, name: String, vid: Int, pid: Int) {
        out.append("    const val ${name}_VENDOR_ID = $vid\n")
        out.append("    const val ${name}_PRODUCT_ID = $pid\n")
    }

    // ---- one FiiO-family record -------------------------------------------------------------------------------------

    private fun fiioRecord(out: StringBuilder, file: String, rec: Map<String, Any?>) {
        val id = str(rec, "id", file)
        val at = id
        val usb = obj(field(rec, "usb", at), "$at.usb")
        val driver = obj(field(rec, "driver", at), "$at.driver")
        val peq = obj(field(rec, "peq", at), "$at.peq")
        val preamp = obj(field(rec, "preamp", at), "$at.preamp")
        val slots = obj(field(rec, "slots", at), "$at.slots")
        val pacing = obj(field(rec, "pacing", at), "$at.pacing")
        val readback = obj(field(rec, "readback", at), "$at.readback")
        val upstream = obj(field(rec, "upstream", at), "$at.upstream")
        for ((name, section) in listOf("driver" to driver, "peq" to peq, "preamp" to preamp, "slots" to slots, "pacing" to pacing,
            "readback" to readback, "upstream" to upstream)) noUnknown(section, "$at.$name")
        noUnknown(field(rec, "settings", at), "$at.settings")
        noUnknown(field(rec, "info", at), "$at.info")
        noUnknown(field(rec, "preview", at), "$at.preview")
        for (k in listOf("vid", "pid", "productName")) noUnknown(field(usb, k, "$at.usb"), "$at.usb.$k")
        noUnknown(field(rec, "productName", at), "$at.productName")

        val name = ident(id)
        val vid = usbId(field(usb, "vid", "$at.usb"), "$at.usb.vid")
        val pid = usbId(field(usb, "pid", "$at.usb"), "$at.usb.pid")
        val productName = str(rec, "productName", at)
        val shortName = strOrNull(rec, "shortName", at)

        val gain = range(peq, "gainDb", "$at.peq")
        val q = range(peq, "q", "$at.peq")
        val freq = range(peq, "freqHz", "$at.peq")
        val bands = int(peq, "bands", "$at.peq")
        if (bands < 1) fail("$at.peq.bands must be at least 1")
        val offset = dbl(preamp, "registerOffsetDb", "$at.preamp")
        val preampDb = range(preamp, "db", "$at.preamp")
        // FiioConfig derives the acoustic preamp range as gain range minus register offset; the record must say the same.
        if (!close(preampDb.first, gain.first - offset) || !close(preampDb.second, gain.second - offset)) {
            fail("$at.preamp.db ${preampDb} does not equal peq.gainDb ${gain} minus registerOffsetDb $offset")
        }
        if (!bool(preamp, "present", "$at.preamp")) fail("$at.preamp.present must be true for a fiio record")

        val typeCodes = typeMap(obj(field(peq, "types", "$at.peq"), "$at.peq.types"), "$at.peq.types")
        if (typeCodes.isEmpty()) fail("$at.peq.types must offer at least one type")
        val shelfQScale = qScale(peq, "shelfQScale", "$at.peq")
        val peakQScale = qScale(peq, "peakQScale", "$at.peq")

        val qSlack = when (val s = str(readback, "qSlack", "$at.readback")) {
            "fiio-1+q/250" -> true
            "none" -> false
            else -> fail("$at.readback.qSlack \"$s\" is not known to the fiio driver (fiio-1+q/250 | none)")
        }
        val names = str(slots, "names", "$at.slots")
        val userSlotNames = names == "device-by-index" || names == "device-by-slot"
        val nameBySlotId = names == "device-by-slot"
        if (!userSlotNames && names != "app" && names != "none") fail("$at.slots.names \"$names\" is not known to the fiio driver")

        val labels = obj(field(slots, "labels", "$at.slots"), "$at.slots.labels")
        val labelText = labels.entries.joinToString(", ") { (k, v) ->
            "${k.toIntOrNull() ?: fail("$at.slots.labels key \"$k\" is not a slot number")} to ${ks(v as? String ?: fail("$at.slots.labels.$k must be a string"))}"
        }

        val capture: String = when (val c = field(driver, "capture", "$at.driver")) {
            null -> "null"
            else -> {
                val cm = obj(c, "$at.driver.capture")
                "FiioCaptureIdentity(${name}_VENDOR_ID, ${name}_PRODUCT_ID, ${ks(str(usb, "productName", "$at.usb"))}, ${ks(str(cm, "fixturePath", "$at.driver.capture"))})"
            }
        }

        val placements = list(field(rec, "settings", at), "$at.settings").mapIndexed { i, e ->
            val p = obj(e, "$at.settings[$i]")
            "SettingPlacement(${ks(str(p, "id", "$at.settings[$i]"))}, ${strOrNullLit(p, "section", "$at.settings[$i]")}, " +
                "${int(p, "group", "$at.settings[$i]")}, ${bool(p, "writeVerified", "$at.settings[$i]")})"
        }
        val infoIds = list(field(rec, "info", at), "$at.info").mapIndexed { i, e -> ks(e as? String ?: fail("$at.info[$i] must be a string")) }
        val preview = obj(field(rec, "preview", at), "$at.preview").entries.map { (k, v) ->
            "${ks(k)} to ${(v as? Int) ?: fail("$at.preview.$k must be an integer")}"
        }

        out.append("\n    // ---- $id (devices/${file}) ----\n")
        idConsts(out, name, vid, pid)
        out.append("\n    val $name: FiioConfig = FiioConfig(\n")
        fun p(k: String, v: String) = out.append("        $k = $v,\n")
        p("productName", ks(productName))
        p("vendorIds", setOfInts(list(field(upstream, "vendorIds", "$at.upstream"), "$at.upstream.vendorIds").map { (it as? Int) ?: fail("$at.upstream.vendorIds must hold integers") }))
        p("reportId", int(driver, "reportId", "$at.driver").toString())
        p("maxFilters", bands.toString())
        p("minGainDb", dl(gain.first)); p("maxGainDb", dl(gain.second))
        p("minQ", dl(q.first)); p("maxQ", dl(q.second))
        p("saveCommand", int(driver, "saveCommand", "$at.driver").toString())
        p("userSlots", setOfInts(intList(slots, "user", "$at.slots")))
        p("declaredWritableSlots", setOfInts(intList(slots, "declaredWritable", "$at.slots")))
        p("stockSlots", setOfInts(intList(slots, "stock", "$at.slots")))
        p("slotLabels", if (labels.isEmpty()) "emptyMap()" else "mapOf($labelText)")
        p("bypassSlot", intOrNull(slots, "bypass", "$at.slots")?.toString() ?: "null")
        p("disconnectOnSave", bool(driver, "disconnectOnSave", "$at.driver").toString())
        p("peakingGainCompensation", bool(driver, "peakingGainCompensation", "$at.driver").toString())
        p("shelfAlphaCompensation", bool(driver, "shelfAlphaCompensation", "$at.driver").toString())
        p("sourceUrl", ks(str(upstream, "sourceUrl", "$at.upstream")))
        p("constraintsUrl", ks(str(upstream, "constraintsUrl", "$at.upstream")))
        p("constraintsRef", ks(str(upstream, "constraintsRef", "$at.upstream")))
        p("upstreamExperimental", bool(upstream, "experimental", "$at.upstream").toString())
        p("bestGuessProductName", bool(upstream, "bestGuessProductName", "$at.upstream").toString())
        p("capture", capture)
        p("codecBlockers", stringList(upstream, "codecBlockers", "$at.upstream"))
        p("evidenceCaveats", stringList(upstream, "evidenceCaveats", "$at.upstream"))
        p("status", ks(str(upstream, "status", "$at.upstream")))
        p("typeCodes", "mapOf(" + typeCodes.joinToString(", ") { (t, c) -> "FilterType.$t to $c" } + ")")
        p("minFrequencyHz", freq.first.let { whole(it, "$at.peq.freqHz") }.toString())
        p("maxFrequencyHz", freq.second.let { whole(it, "$at.peq.freqHz") }.toString())
        p("fixedBandCount", bool(peq, "fixedBandCount", "$at.peq").toString())
        p("qReadbackSlack", qSlack.toString())
        p("consumeWriteEchoes", bool(pacing, "consumeEchoes", "$at.pacing").toString())
        p("writeGapMs", int(pacing, "writeGapMs", "$at.pacing").toString())
        p("afterSaveMs", int(pacing, "afterSaveMs", "$at.pacing").toString())
        p("checksumFrames", bool(pacing, "checksum", "$at.pacing").toString())
        p("needsAudioStream", bool(pacing, "needsAudioStream", "$at.pacing").toString())
        p("userSlotNames", userSlotNames.toString())
        p("userSlotPicker", bool(slots, "picker", "$at.slots").toString())
        p("shelfQScale", shelfQScale)
        p("peakQScale", peakQScale)
        p("preampOffsetDb", dl(offset))
        p("preampWholeDb", bool(preamp, "wholeDb", "$at.preamp").toString())
        p("hardwareVerified", bool(driver, "hardwareVerified", "$at.driver").toString())
        p("snowskyExchange", bool(driver, "snowskyExchange", "$at.driver").toString())
        p("shortName", if (shortName == null) "null" else ks(shortName))
        p("nameBySlotId", nameBySlotId.toString())
        p("nameLength", int(slots, "nameLength", "$at.slots").toString())
        p("settings", if (placements.isEmpty()) "emptyList()" else "DacSettings.forModel(listOf(\n" + placements.joinToString("") { "            $it,\n" } + "        ))")
        p("probeGapMs", intOrNull(pacing, "probeGapMs", "$at.pacing")?.toString() ?: "null")
        p("info", if (infoIds.isEmpty()) "emptyList()" else "DacSettings.infoFor(listOf(${infoIds.joinToString(", ")}))")
        p("settingsPreview", if (preview.isEmpty()) "emptyMap()" else "mapOf(${preview.joinToString(", ")})")
        out.append("    )\n")
    }

    // ---- one WalkPlay record: stable (Micro, Max, TRN) = the caps, preamp policy, factory flat and read bounds the strict path needs ------------

    private fun walkplayRecord(out: StringBuilder, file: String, rec: Map<String, Any?>) {
        val at = str(rec, "id", file)
        val usb = obj(field(rec, "usb", at), "$at.usb")
        val driver = obj(field(rec, "driver", at), "$at.driver")
        val peq = obj(field(rec, "peq", at), "$at.peq")
        val preamp = obj(field(rec, "preamp", at), "$at.preamp")
        val slots = obj(field(rec, "slots", at), "$at.slots")
        for (k in listOf("reportId", "schemeNo", "bandLen", "writeSequence", "designRateHz")) noUnknown(field(driver, k, "$at.driver"), "$at.driver.$k")
        for (k in listOf("bands", "freqHz", "gainDb", "q", "types", "shelfQScale", "coefficientRateHz")) noUnknown(field(peq, k, "$at.peq"), "$at.peq.$k")
        for (k in listOf("present", "db", "wholeDb")) noUnknown(field(preamp, k, "$at.preamp"), "$at.preamp.$k")
        noUnknown(field(slots, "factoryFlat", "$at.slots"), "$at.slots.factoryFlat")
        noUnknown(field(rec, "name", at), "$at.name")

        val name = ident(at)
        val vid = usbId(field(usb, "vid", "$at.usb"), "$at.usb.vid")
        val pid = usbId(field(usb, "pid", "$at.usb"), "$at.usb.pid")
        val bands = int(peq, "bands", "$at.peq")
        if (bands < 1) fail("$at.peq.bands must be at least 1")
        val gain = range(peq, "gainDb", "$at.peq"); val q = range(peq, "q", "$at.peq"); val freq = range(peq, "freqHz", "$at.peq")
        val types = typeMap(obj(field(peq, "types", "$at.peq"), "$at.peq.types"), "$at.peq.types")
        if (types.isEmpty()) fail("$at.peq.types must offer at least one type")
        if (!bool(preamp, "present", "$at.preamp")) fail("$at.preamp.present must be true for a stable walkplay record")
        val wholeDb = bool(preamp, "wholeDb", "$at.preamp")
        val preampDb = range(preamp, "db", "$at.preamp")
        if (wholeDb && (preampDb.first != Math.rint(preampDb.first) || preampDb.second != Math.rint(preampDb.second))) fail("$at.preamp.db must be whole dB when preamp.wholeDb is true")
        val flat = list(field(slots, "factoryFlat", "$at.slots"), "$at.slots.factoryFlat").mapIndexed { i, e ->
            val row = list(e, "$at.slots.factoryFlat[$i]")
            if (row.size != 3 || row[0] !is Int || row[1] !is Number || row[2] != "PEAK") fail("$at.slots.factoryFlat[$i] must be [frequency Hz, Q, \"PEAK\"] (a flat band is a peak at 0 dB)")
            "FlatBand(${row[0]}, ${dl((row[1] as Number).toDouble())})"
        }
        if (flat.size != bands) fail("$at.slots.factoryFlat has ${flat.size} rows but peq.bands is $bands")
        val readback = obj(field(rec, "readback", at), "$at.readback")
        val readBounds = if (readback.containsKey("readBoundsHz") || readback.containsKey("readBoundsDb")) {
            noUnknown(field(readback, "readBoundsHz", "$at.readback"), "$at.readback.readBoundsHz")
            noUnknown(field(readback, "readBoundsDb", "$at.readback"), "$at.readback.readBoundsDb")
            val hz = range(readback, "readBoundsHz", "$at.readback"); val db = range(readback, "readBoundsDb", "$at.readback")
            "${whole(hz.first, "$at.readback.readBoundsHz")}..${whole(hz.second, "$at.readback.readBoundsHz")}" to "${dl(db.first)}..${dl(db.second)}"
        } else null
        val usbName = (field(usb, "productName", "$at.usb") as? String)?.takeIf { it != "unknown" }

        out.append("\n    // ---- $at (devices/${file}): WalkPlay, stable ----\n")
        idConsts(out, name, vid, pid)
        out.append("    const val ${name}_REPORT_ID = ${int(driver, "reportId", "$at.driver")}\n")
        out.append("    const val ${name}_BANDS = $bands\n")
        out.append("    const val ${name}_BAND_LEN = ${int(driver, "bandLen", "$at.driver")}\n")
        out.append("    const val ${name}_DESIGN_RATE_HZ = ${dl(int(driver, "designRateHz", "$at.driver").toDouble())}\n")
        out.append("    const val ${name}_PREAMP_MIN_DB = ${preampDb.first.toInt()}\n")
        out.append("    const val ${name}_PREAMP_MAX_DB = ${preampDb.second.toInt()}\n\n")
        out.append("    val $name: WalkPlayData = WalkPlayData(\n")
        fun p(k: String, v: String) = out.append("        $k = $v,\n")
        p("id", ks(at)); p("name", ks(str(rec, "name", at))); p("vendorId", "${name}_VENDOR_ID"); p("productId", "${name}_PRODUCT_ID")
        p("usbName", usbName?.let { ks(it) } ?: "null")
        p("schemeNo", int(driver, "schemeNo", "$at.driver").toString()); p("reportId", "${name}_REPORT_ID"); p("bandLen", "${name}_BAND_LEN"); p("bands", "${name}_BANDS")
        p("gainMinDb", dl(gain.first)); p("gainMaxDb", dl(gain.second)); p("qMin", dl(q.first)); p("qMax", dl(q.second))
        p("freqMinHz", dl(freq.first)); p("freqMaxHz", dl(freq.second))
        p("types", "setOf(" + types.joinToString(", ") { "FilterType.${it.first}" } + ")")
        p("shelfQScale", qScale(peq, "shelfQScale", "$at.peq")); p("coefficientRateHz", rateHz(peq, "coefficientRateHz", "$at.peq"))
        p("preampWholeDb", wholeDb.toString()); p("preampMinDb", "${name}_PREAMP_MIN_DB"); p("preampMaxDb", "${name}_PREAMP_MAX_DB")
        p("factoryFlat", "listOf(" + flat.joinToString(", ") + ")")
        p("readBoundsHz", readBounds?.first ?: "null"); p("readBoundsDb", readBounds?.second ?: "null")
        out.append("    )\n")
    }

    // ---- the WalkPlay record of a device that is read only: only what the read-only profile and its caps need ----------------------------------------

    private fun readOnlyWalkplayRecord(out: StringBuilder, file: String, rec: Map<String, Any?>) {
        val at = str(rec, "id", file)
        val usb = obj(field(rec, "usb", at), "$at.usb")
        val driver = obj(field(rec, "driver", at), "$at.driver")
        val peq = obj(field(rec, "peq", at), "$at.peq")
        for (k in listOf("reportId", "schemeNo")) noUnknown(field(driver, k, "$at.driver"), "$at.driver.$k")
        for (k in listOf("bands", "gainDb", "q", "types", "coefficientRateHz")) noUnknown(field(peq, k, "$at.peq"), "$at.peq.$k")
        for (k in listOf("vid", "pid", "productName")) noUnknown(field(usb, k, "$at.usb"), "$at.usb.$k")
        noUnknown(field(rec, "name", at), "$at.name")
        val name = ident(at)
        val vid = usbId(field(usb, "vid", "$at.usb"), "$at.usb.vid")
        val pid = usbId(field(usb, "pid", "$at.usb"), "$at.usb.pid")
        val bands = int(peq, "bands", "$at.peq")
        val gain = range(peq, "gainDb", "$at.peq"); val q = range(peq, "q", "$at.peq")
        val types = typeMap(obj(field(peq, "types", "$at.peq"), "$at.peq.types"), "$at.peq.types")
        if (types.isEmpty()) fail("$at.peq.types must offer at least one type")

        out.append("\n    // ---- $at (devices/${file}): WalkPlay, read only ----\n")
        idConsts(out, name, vid, pid)
        out.append("\n    val $name: ReadOnlyWalkPlayData = ReadOnlyWalkPlayData(\n")
        fun p(k: String, v: String) = out.append("        $k = $v,\n")
        p("id", ks(at)); p("name", ks(str(rec, "name", at))); p("vendorId", "${name}_VENDOR_ID"); p("productId", "${name}_PRODUCT_ID")
        p("usbName", ks(str(usb, "productName", "$at.usb")))
        p("schemeNo", int(driver, "schemeNo", "$at.driver").toString()); p("reportId", int(driver, "reportId", "$at.driver").toString()); p("bands", bands.toString())
        p("gainMinDb", dl(gain.first)); p("gainMaxDb", dl(gain.second)); p("qMin", dl(q.first)); p("qMax", dl(q.second))
        p("types", "setOf(" + types.joinToString(", ") { "FilterType.${it.first}" } + ")")
        p("coefficientRateHz", rateHz(peq, "coefficientRateHz", "$at.peq"))
        out.append("    )\n")
    }

    // ---- one Moondrop record ----------------------------------------------------------------------------------------------------------------------

    private fun moondropRecord(out: StringBuilder, file: String, rec: Map<String, Any?>) {
        val at = str(rec, "id", file)
        val usb = obj(field(rec, "usb", at), "$at.usb")
        val driver = obj(field(rec, "driver", at), "$at.driver")
        val peq = obj(field(rec, "peq", at), "$at.peq")
        val preamp = obj(field(rec, "preamp", at), "$at.preamp")
        val pacing = obj(field(rec, "pacing", at), "$at.pacing")
        val slots = obj(field(rec, "slots", at), "$at.slots")
        noUnknown(field(slots, "writableIndexes", "$at.slots"), "$at.slots.writableIndexes")
        val writableIndexes = intList(slots, "writableIndexes", "$at.slots")
        if (writableIndexes.isEmpty() || writableIndexes.any { it !in 0..255 } || writableIndexes.toSet().size != writableIndexes.size)
            fail("$at.slots.writableIndexes must list distinct EQ indexes 0..255")
        if (int(driver, "peqBank", "$at.driver") !in writableIndexes) fail("$at.driver.peqBank must be one of slots.writableIndexes $writableIndexes")
        for (k in listOf("reportId", "reportBytes", "peqBank", "globalGainRegister", "preGainRegister", "eqIndexRegister", "saveEqCommand", "designRateHz"))
            noUnknown(field(driver, k, "$at.driver"), "$at.driver.$k")
        for (k in listOf("bands", "freqHz", "gainDb", "q", "types", "heldTypes", "shelfQScale")) noUnknown(field(peq, k, "$at.peq"), "$at.peq.$k")
        for (k in listOf("present", "db", "globalGain")) noUnknown(field(preamp, k, "$at.preamp"), "$at.preamp.$k")
        for (k in listOf("writeGapMs", "opGapMs", "afterSaveMs", "afterSelectMs")) noUnknown(field(pacing, k, "$at.pacing"), "$at.pacing.$k")
        for (k in listOf("vid", "pid", "productName")) noUnknown(field(usb, k, "$at.usb"), "$at.usb.$k")
        noUnknown(field(rec, "name", at), "$at.name")
        val name = ident(at)
        val vid = usbId(field(usb, "vid", "$at.usb"), "$at.usb.vid")
        val pid = usbId(field(usb, "pid", "$at.usb"), "$at.usb.pid")
        val gain = range(peq, "gainDb", "$at.peq"); val q = range(peq, "q", "$at.peq"); val freq = range(peq, "freqHz", "$at.peq")
        val offered = typeMap(obj(field(peq, "types", "$at.peq"), "$at.peq.types"), "$at.peq.types")
        if (offered.isEmpty()) fail("$at.peq.types must offer at least one type")
        val held = typeMap(obj(field(peq, "heldTypes", "$at.peq"), "$at.peq.heldTypes"), "$at.peq.heldTypes")
        val native = (offered + held).sortedBy { it.second }
        if (native.map { it.second }.toSet().size != native.size) fail("$at.peq.types and heldTypes share a native code")
        if (!bool(preamp, "present", "$at.preamp")) fail("$at.preamp.present must be true for the moondrop record")
        val preGain = range(preamp, "db", "$at.preamp")
        val gg = obj(field(preamp, "globalGain", "$at.preamp"), "$at.preamp.globalGain")
        noUnknown(gg, "$at.preamp.globalGain")
        val globalGain = range(gg, "rangeDb", "$at.preamp.globalGain")
        val ggRegister = hexInt(field(gg, "register", "$at.preamp.globalGain"), "$at.preamp.globalGain.register")
        if (ggRegister != hexInt(field(driver, "globalGainRegister", "$at.driver"), "$at.driver.globalGainRegister")) fail("$at.preamp.globalGain.register differs from driver.globalGainRegister")

        out.append("\n    // ---- $at (devices/${file}): Moondrop ----\n")
        idConsts(out, name, vid, pid)
        out.append("    const val ${name}_REPORT_ID = ${int(driver, "reportId", "$at.driver")}\n")
        out.append("    const val ${name}_CMD_EQ_ACTIVE = ${hex(hexInt(field(driver, "eqIndexRegister", "$at.driver"), "$at.driver.eqIndexRegister"))}\n")
        out.append("    const val ${name}_CMD_GLOBAL_GAIN = ${hex(ggRegister)}\n")
        out.append("    const val ${name}_CMD_PRE_GAIN = ${hex(hexInt(field(driver, "preGainRegister", "$at.driver"), "$at.driver.preGainRegister"))}\n")
        out.append("    const val ${name}_CMD_EQ_SAVE = ${hex(hexInt(field(driver, "saveEqCommand", "$at.driver"), "$at.driver.saveEqCommand"))}\n")
        out.append("    const val ${name}_DELAY_BAND_MS = ${int(pacing, "writeGapMs", "$at.pacing")}L\n")
        out.append("    const val ${name}_DELAY_OP_MS = ${int(pacing, "opGapMs", "$at.pacing")}L\n")
        out.append("    const val ${name}_DELAY_FLASH_MS = ${int(pacing, "afterSaveMs", "$at.pacing")}L\n")
        out.append("    const val ${name}_DELAY_EQ_INDEX_MS = ${int(pacing, "afterSelectMs", "$at.pacing")}L\n")
        out.append("    const val ${name}_DESIGN_RATE_HZ = ${dl(int(driver, "designRateHz", "$at.driver").toDouble())}\n\n")
        out.append("    val $name: MoondropData = MoondropData(\n")
        fun p(k: String, v: String) = out.append("        $k = $v,\n")
        p("name", ks(str(rec, "name", at))); p("vendorId", "${name}_VENDOR_ID"); p("productId", "${name}_PRODUCT_ID"); p("productName", ks(str(usb, "productName", "$at.usb")))
        p("reportId", "${name}_REPORT_ID"); p("reportBytes", int(driver, "reportBytes", "$at.driver").toString()); p("writableIndex", int(driver, "peqBank", "$at.driver").toString()); p("writableIndexes", setOfInts(writableIndexes))
        p("bands", int(peq, "bands", "$at.peq").toString())
        p("gainMinDb", dl(gain.first)); p("gainMaxDb", dl(gain.second)); p("qMin", dl(q.first)); p("qMax", dl(q.second)); p("freqMinHz", dl(freq.first)); p("freqMaxHz", dl(freq.second))
        p("offeredTypes", "setOf(" + offered.joinToString(", ") { "FilterType.${it.first}" } + ")")
        p("nativeTypes", "mapOf(" + native.joinToString(", ") { "${it.second} to FilterType.${it.first}" } + ")")
        p("shelfQScale", qScale(peq, "shelfQScale", "$at.peq"))
        p("preGainMinDb", dl(preGain.first)); p("preGainMaxDb", dl(preGain.second)); p("globalGainMinDb", dl(globalGain.first)); p("globalGainMaxDb", dl(globalGain.second))
        out.append("    )\n")
    }

    // ---- one KT Micro record ----------------------------------------------------------------------------------------------------------------------

    private fun ktmicroRecord(out: StringBuilder, file: String, rec: Map<String, Any?>) {
        val at = str(rec, "id", file)
        val usb = obj(field(rec, "usb", at), "$at.usb")
        val driver = obj(field(rec, "driver", at), "$at.driver")
        val peq = obj(field(rec, "peq", at), "$at.peq")
        val preamp = obj(field(rec, "preamp", at), "$at.preamp")
        for (k in listOf("reportId", "payloadBytes", "readOp", "bandRegisters", "writeAck", "eqEnableRegister", "eqEnableOn", "eqEnableOff", "saveCommand", "digitalGainRegister", "globalGainRegister"))
            noUnknown(field(driver, k, "$at.driver"), "$at.driver.$k")
        for (k in listOf("bands", "freqHz", "gainDb", "q", "types", "designRateHz", "assumedStreamHz")) noUnknown(field(peq, k, "$at.peq"), "$at.peq.$k")
        noUnknown(field(preamp, "globalGain", "$at.preamp"), "$at.preamp.globalGain")
        for (k in listOf("vid", "pid", "productName", "matchByName")) noUnknown(field(usb, k, "$at.usb"), "$at.usb.$k")
        noUnknown(field(rec, "name", at), "$at.name")
        val name = ident(at)
        val vid = usbId(field(usb, "vid", "$at.usb"), "$at.usb.vid")
        val pid = usbId(field(usb, "pid", "$at.usb"), "$at.usb.pid")
        val gain = range(peq, "gainDb", "$at.peq"); val q = range(peq, "q", "$at.peq"); val freq = range(peq, "freqHz", "$at.peq")
        val types = typeMap(obj(field(peq, "types", "$at.peq"), "$at.peq.types"), "$at.peq.types")
        if (types.isEmpty()) fail("$at.peq.types must offer at least one type")
        val br = obj(field(driver, "bandRegisters", "$at.driver"), "$at.driver.bandRegisters")
        if (int(br, "perBand", "$at.driver.bandRegisters") != 2 || list(field(br, "layout", "$at.driver.bandRegisters"), "$at.driver.bandRegisters.layout") != listOf("gainFrequency", "qType"))
            fail("$at.driver.bandRegisters: the generator knows one gain-and-frequency register and one Q-and-type register per band (perBand 2) only")
        val gg = obj(field(preamp, "globalGain", "$at.preamp"), "$at.preamp.globalGain")
        noUnknown(gg, "$at.preamp.globalGain")
        val steps = intList(gg, "userSteps", "$at.preamp.globalGain")
        if (steps.size != 2 || steps[0] > steps[1]) fail("$at.preamp.globalGain.userSteps must be [first, last]")
        val ggRegister = hexInt(field(gg, "register", "$at.preamp.globalGain"), "$at.preamp.globalGain.register")
        if (ggRegister != hexInt(field(driver, "globalGainRegister", "$at.driver"), "$at.driver.globalGainRegister")) fail("$at.preamp.globalGain.register differs from driver.globalGainRegister")
        val aliases = list(field(usb, "nameAliases", "$at.usb"), "$at.usb.nameAliases").map { ks(it as? String ?: fail("$at.usb.nameAliases must hold strings")) }
        if (!bool(usb, "matchByName", "$at.usb")) fail("$at.usb.matchByName must be true: the KT driver is selected by the USB name")

        out.append("\n    // ---- $at (devices/${file}): KT Micro ----\n")
        idConsts(out, name, vid, pid)
        out.append("    const val ${name}_REPORT_ID = ${int(driver, "reportId", "$at.driver")}\n")
        out.append("    const val ${name}_PAYLOAD_BYTES = ${int(driver, "payloadBytes", "$at.driver")}\n")
        out.append("    const val ${name}_READ_OP = ${hex(hexInt(field(driver, "readOp", "$at.driver"), "$at.driver.readOp"))}\n")
        out.append("    const val ${name}_SAVE_COMMAND = ${hex(hexInt(field(driver, "saveCommand", "$at.driver"), "$at.driver.saveCommand"))}\n")
        out.append("    const val ${name}_EQ_ENABLE_REGISTER = ${hex(hexInt(field(driver, "eqEnableRegister", "$at.driver"), "$at.driver.eqEnableRegister"))}\n")
        out.append("    const val ${name}_EQ_ON = ${int(driver, "eqEnableOn", "$at.driver")}\n")
        out.append("    const val ${name}_EQ_OFF = ${int(driver, "eqEnableOff", "$at.driver")}\n")
        out.append("    const val ${name}_DIGITAL_GAIN_REGISTER = ${hex(hexInt(field(driver, "digitalGainRegister", "$at.driver"), "$at.driver.digitalGainRegister"))}\n")
        out.append("    const val ${name}_GLOBAL_GAIN_REGISTER = ${hex(ggRegister)}\n\n")
        out.append("    val $name: KtMicroData = KtMicroData(\n")
        fun p(k: String, v: String) = out.append("        $k = $v,\n")
        p("name", ks(str(rec, "name", at))); p("vendorId", "${name}_VENDOR_ID"); p("productId", "${name}_PRODUCT_ID"); p("productName", ks(str(usb, "productName", "$at.usb")))
        p("nameAliases", if (aliases.isEmpty()) "emptyList()" else "listOf(" + aliases.joinToString(", ") + ")")
        p("bands", int(peq, "bands", "$at.peq").toString())
        p("gainMinDb", dl(gain.first)); p("gainMaxDb", dl(gain.second)); p("qMin", dl(q.first)); p("qMax", dl(q.second)); p("freqMinHz", dl(freq.first)); p("freqMaxHz", dl(freq.second))
        p("types", "setOf(" + types.joinToString(", ") { "FilterType.${it.first}" } + ")")
        p("bandRegisterBase", hex(hexInt(field(br, "base", "$at.driver.bandRegisters"), "$at.driver.bandRegisters.base")))
        p("enableRegister", "${name}_EQ_ENABLE_REGISTER"); p("digitalGainRegister", "${name}_DIGITAL_GAIN_REGISTER")
        p("writeAck", int(driver, "writeAck", "$at.driver").toString())
        p("globalGainUserSteps", "${steps[0]}..${steps[1]}")
        p("designRateHz", rateHz(peq, "designRateHz", "$at.peq")); p("assumedStreamHz", rateHz(peq, "assumedStreamHz", "$at.peq"))
        out.append("    )\n")
    }

    // ---- reading helpers: every miss is a build failure with the record and the path ------------------------------------

    private fun fail(msg: String): Nothing = throw GradleException("devices/*.json: $msg")

    @Suppress("UNCHECKED_CAST")
    private fun obj(v: Any?, at: String): Map<String, Any?> = (v as? Map<String, Any?>) ?: fail("$at must be an object")

    private fun list(v: Any?, at: String): List<Any?> = (v as? List<Any?>) ?: fail("$at must be an array")

    private fun field(m: Map<String, Any?>, key: String, at: String): Any? {
        if (!m.containsKey(key)) fail("$at.$key is missing")
        return m[key]
    }

    private fun str(m: Map<String, Any?>, key: String, at: String): String = (field(m, key, at) as? String) ?: fail("$at.$key must be a string")

    private fun strOrNull(m: Map<String, Any?>, key: String, at: String): String? = when (val v = field(m, key, at)) {
        null -> null
        is String -> v
        else -> fail("$at.$key must be a string or null")
    }

    private fun strOrNullLit(m: Map<String, Any?>, key: String, at: String): String = strOrNull(m, key, at)?.let { ks(it) } ?: "null"

    private fun int(m: Map<String, Any?>, key: String, at: String): Int = (field(m, key, at) as? Int) ?: fail("$at.$key must be an integer")

    private fun intOrNull(m: Map<String, Any?>, key: String, at: String): Int? = when (val v = field(m, key, at)) {
        null -> null
        is Int -> v
        else -> fail("$at.$key must be an integer or null")
    }

    private fun bool(m: Map<String, Any?>, key: String, at: String): Boolean = (field(m, key, at) as? Boolean) ?: fail("$at.$key must be true or false")

    private fun dbl(m: Map<String, Any?>, key: String, at: String): Double = (field(m, key, at) as? Number)?.toDouble() ?: fail("$at.$key must be a number")

    private fun range(m: Map<String, Any?>, key: String, at: String): Pair<Double, Double> {
        val l = list(field(m, key, at), "$at.$key")
        if (l.size != 2 || l.any { it !is Number }) fail("$at.$key must be [min, max]")
        val a = (l[0] as Number).toDouble(); val b = (l[1] as Number).toDouble()
        if (a > b) fail("$at.$key min is above max")
        return a to b
    }

    private fun intList(m: Map<String, Any?>, key: String, at: String): List<Int> =
        list(field(m, key, at), "$at.$key").map { (it as? Int) ?: fail("$at.$key must hold integers") }

    private fun stringList(m: Map<String, Any?>, key: String, at: String): String {
        val l = list(field(m, key, at), "$at.$key").map { ks(it as? String ?: fail("$at.$key must hold strings")) }
        return if (l.isEmpty()) "emptyList()" else "listOf(" + l.joinToString(", ") + ")"
    }

    private val filterTypes = setOf("PEAK", "LOW_SHELF", "HIGH_SHELF", "LOW_PASS", "HIGH_PASS", "BAND_PASS", "ALL_PASS")

    private fun typeMap(m: Map<String, Any?>, at: String): List<Pair<String, Int>> =
        m.entries.map { (k, v) ->
            if (k !in filterTypes) fail("$at.$k is not a FilterType (${filterTypes.joinToString(" | ")})")
            k to ((v as? Int) ?: fail("$at.$k must be an integer code"))
        }

    /** "0x2972" or a plain integer. */
    private fun usbId(v: Any?, at: String): Int = when (v) {
        is Int -> v
        is String -> runCatching { Integer.decode(v) }.getOrNull() ?: fail("$at \"$v\" is not a number")
        else -> fail("$at must be a hex string or an integer")
    }

    /** A register or command byte: "0x24" or a plain integer. */
    private fun hexInt(v: Any?, at: String): Int = usbId(v, at).also { if (it !in 0..255) fail("$at $it is not a byte") }

    private fun whole(d: Double, at: String): Int = if (d == Math.rint(d)) d.toInt() else fail("$at must be whole numbers")

    private fun close(a: Double, b: Double) = Math.abs(a - b) < 1e-9

    private fun noUnknown(v: Any?, at: String) {
        when (v) {
            "unknown" -> fail("$at is \"unknown\" but its driver needs a value; fill it from evidence (a bench log or vendor code), or keep the code value in core/devices/PendingRecords.kt - do not default it here")
            is Map<*, *> -> v.forEach { (k, x) -> noUnknown(x, "$at.$k") }
            is List<*> -> v.forEachIndexed { i, x -> noUnknown(x, "$at[$i]") }
        }
    }

    // ---- emitting helpers ----------------------------------------------------------------------------------------------

    private fun ident(id: String): String {
        if (!Regex("[a-z][a-z0-9-]*").matches(id)) fail("record id \"$id\" must be lower-case letters, digits and dashes")
        return id.uppercase().replace('-', '_')
    }

    private fun dl(d: Double): String = d.toString()

    /**
     * A register-over-intended Q factor (`peq.shelfQScale`, `peq.peakQScale`): a positive finite number, or "sqrt2" for the factor the KA15 and the TRN were measured at.
     * "sqrt2" is emitted as the expression `sqrt(2.0)`, never a rounded literal (a literal would change the register bytes).
     */
    private fun qScale(m: Map<String, Any?>, key: String, at: String): String = when (val v = field(m, key, at)) {
        "sqrt2" -> "sqrt(2.0)"
        is Number -> if (v.toDouble().isFinite() && v.toDouble() > 0) dl(v.toDouble()) else fail("$at.$key must be a positive number or \"sqrt2\"")
        else -> fail("$at.$key must be a number or \"sqrt2\"")
    }

    /** The rate (Hz) the DSP runs the biquad coefficients at (`peq.coefficientRateHz`): a positive finite number. */
    private fun rateHz(m: Map<String, Any?>, key: String, at: String): String = when (val v = field(m, key, at)) {
        is Number -> if (v.toDouble().isFinite() && v.toDouble() > 0) dl(v.toDouble()) else fail("$at.$key must be a positive number of Hz")
        else -> fail("$at.$key must be a number of Hz")
    }

    private fun hex(i: Int): String = "0x%02X".format(i)

    private fun setOfInts(l: List<Int>): String = if (l.isEmpty()) "emptySet()" else "setOf(" + l.joinToString(", ") + ")"

    private fun ks(s: String): String = buildString {
        append('"')
        for (c in s) when (c) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> append(c)
        }
        append('"')
    }
}

